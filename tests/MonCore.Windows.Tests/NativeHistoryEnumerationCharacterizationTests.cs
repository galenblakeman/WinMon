using System.Diagnostics;
using System.Reflection;
using MonCore.Monitoring;
using MonCore.Windows.Monitoring;
using NUnit.Framework;

namespace MonCore.Windows.Tests;

[TestFixture, Category("Integration"), NonParallelizable]
public sealed class NativeHistoryEnumerationCharacterizationTests
{
    private static readonly Func<string, DateTimeOffset, DateTimeOffset, Stopwatch, TimeSpan,
        CancellationToken, IEnumerable<IncidentEvent>> ReadLog = typeof(WindowsHistoryEventReader)
        .GetMethod("ReadLog", BindingFlags.Static | BindingFlags.NonPublic)!
        .CreateDelegate<Func<string, DateTimeOffset, DateTimeOffset, Stopwatch, TimeSpan,
            CancellationToken, IEnumerable<IncidentEvent>>>();

    private IncidentEvent _existing = null!;

    [OneTimeSetUp]
    public void FindExistingCuratedApplicationEventWithoutWritingToTheLog()
    {
        var end = DateTimeOffset.UtcNow;
        using var records = ReadLog("Application", end.AddDays(-30), end, Stopwatch.StartNew(),
            TimeSpan.FromSeconds(5), CancellationToken.None).GetEnumerator();
        if (!records.MoveNext())
            Assert.Ignore("Requires an existing curated Application event in the last thirty days; no event is generated by this fixture.");
        _existing = records.Current;
    }

    [Test]
    public void NativeReadYieldsTheExistingEventAtBothInclusiveRangeBoundaries()
    {
        var result = new WindowsHistoryEventReader().Read(_existing.Timestamp, _existing.Timestamp,
            CancellationToken.None);
        Assert.That(result.Coverage.All(item => item.Status == IncidentEventCoverageStatus.Complete), Is.True);
        Assert.That(result.LimitReached, Is.False);
        Assert.That(result.Events.Any(IsExistingEvent), Is.True, "The frozen event must be returned at an exact timestamp boundary.");
        Assert.That(result.Events.All(item => item.Timestamp == _existing.Timestamp), Is.True);
        Assert.That(result.Events.All(item => !item.Message.Contains('\r') && !item.Message.Contains('\n')), Is.True);
    }

    [Test]
    public void NativeReadCancellationAfterYieldRetainsTheCallerToken()
    {
        using var cancellation = new CancellationTokenSource();
        using var records = FrozenRecords(cancellation.Token).GetEnumerator();
        Assert.That(records.MoveNext(), Is.True);
        Assert.That(IsExistingEvent(records.Current), Is.True);
        cancellation.Cancel();
        var error = Assert.Throws<OperationCanceledException>(() => records.MoveNext());
        Assert.That(error!.CancellationToken, Is.EqualTo(cancellation.Token));
        Assert.That(records.MoveNext(), Is.False);
    }

    [Test]
    public void NativeReadEarlyDisposalAllowsAFreshCompleteEnumeration()
    {
        using (var records = FrozenRecords(CancellationToken.None).GetEnumerator())
        {
            Assert.That(records.MoveNext(), Is.True);
            Assert.That(IsExistingEvent(records.Current), Is.True);
        }

        using var reopened = FrozenRecords(CancellationToken.None).GetEnumerator();
        var count = 0;
        var found = false;
        while (reopened.MoveNext())
        {
            Assert.That(reopened.Current.Timestamp == _existing.Timestamp, Is.True);
            found |= IsExistingEvent(reopened.Current);
            Assert.That(++count, Is.LessThanOrEqualTo(WindowsHistoryEventReader.MaximumEvents));
        }
        Assert.That(found, Is.True);
        Assert.That(reopened.MoveNext(), Is.False);
    }

    private IEnumerable<IncidentEvent> FrozenRecords(CancellationToken token) =>
        ReadLog("Application", _existing.Timestamp, _existing.Timestamp, Stopwatch.StartNew(), TimeSpan.FromSeconds(5), token);

    // Avoid exposing machine event messages through assertion diagnostics.
    private bool IsExistingEvent(IncidentEvent item) => item == _existing;
}
